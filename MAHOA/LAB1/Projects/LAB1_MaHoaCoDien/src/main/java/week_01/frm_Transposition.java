    private void btn_encryptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_encryptActionPerformed
        String plaintext = txt_plaintext.getText();
        String keyText = txt_key.getText();

        try {
            int[] key = TranspositionCipher.parseKey(keyText);
            txt_ciphertext.setText(
                    TranspositionCipher.encrypt(plaintext, key)
            );
            lbl_status.setText("Mã hóa hoán vị thành công.");
        } catch (IllegalArgumentException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    ex.getMessage(),
                    "Lỗi mã hóa",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btn_encryptActionPerformed

    private void btn_decryptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_decryptActionPerformed
        String ciphertext = txt_ciphertext.getText();
        String keyText = txt_key.getText();

        try {
            int[] key = TranspositionCipher.parseKey(keyText);
            txt_plaintext.setText(
                    TranspositionCipher.decrypt(ciphertext, key)
            );
            lbl_status.setText("Giải mã hoán vị thành công.");
        } catch (IllegalArgumentException ex) {
            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    ex.getMessage(),
                    "Lỗi giải mã",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btn_decryptActionPerformed

    private void btn_openActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_openActionPerformed
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();

        int result = fileChooser.showOpenDialog(this);

        if (result == javax.swing.JFileChooser.APPROVE_OPTION) {
            try {
                java.io.File file = fileChooser.getSelectedFile();

                String content = java.nio.file.Files.readString(
                        file.toPath(),
                        java.nio.charset.StandardCharsets.UTF_8
                );

                txt_ciphertext.setText(content);
                lbl_status.setText("Đã mở file ciphertext thành công.");
            } catch (java.io.IOException ex) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Không thể mở file: " + ex.getMessage(),
                        "Lỗi",
                        javax.swing.JOptionPane.ERROR_MESSAGE
                );
            }
        }
    }//GEN-LAST:event_btn_openActionPerformed

    private void btn_saveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_saveActionPerformed
        javax.swing.JFileChooser fileChooser = new javax.swing.JFileChooser();

        int result = fileChooser.showSaveDialog(this);

        if (result == javax.swing.JFileChooser.APPROVE_OPTION) {
            try {
                java.io.File file = fileChooser.getSelectedFile();

                java.nio.file.Files.writeString(
                        file.toPath(),
                        txt_ciphertext.getText(),
                        java.nio.charset.StandardCharsets.UTF_8
                );

                lbl_status.setText("Đã lưu file ciphertext thành công.");
            } catch (java.io.IOException ex) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Không thể lưu file: " + ex.getMessage(),
                        "Lỗi",
                        javax.swing.JOptionPane.ERROR_MESSAGE
                );
            }
        }
    }//GEN-LAST:event_btn_saveActionPerformed

